import assert from 'node:assert/strict';
import fs from 'node:fs';
import cp from 'node:child_process';
import {fileURLToPath} from 'node:url';
process.umask(0o077);
const root=fileURLToPath(new URL('.',import.meta.url));
const spec=JSON.parse(fs.readFileSync(root+'images.json')).find(x=>x.key===process.argv[2]);assert(spec);
const rollback=process.argv[3]==='--privacy-rollback';assert(!process.argv[3]||(rollback&&spec.key==='spliit'));
if(rollback)spec.candidate='utilibre-spliit:1.29.0-privacy-rollback-20261011';
const docker=(...args)=>cp.execFileSync('docker',args,{encoding:'utf8'}).trim();
assert.equal(docker('image','inspect','--format','{{.Id}}',spec.base),spec.baseId);
const free=()=>{const s=fs.statfsSync('/');return s.bavail*s.bsize;};assert(free()>8.3*1024**3);
const dir=fs.mkdtempSync('/opt/utilibre/reports/app-leaves-'+spec.key+'-');
const log=fs.openSync(dir+'/build.log','w');
const child=cp.spawn('docker',['build','--pull=false','--build-arg','BASE='+spec.base,'--build-arg','TARGET='+spec.path,'--build-arg','FINAL_USER='+spec.user,'--target',rollback?'privacy-rollback':spec.library==='mysql2'?'mysql-runtime':'zip-runtime','-f',root+'Dockerfile','-t',spec.candidate,root],{stdio:['ignore',log,log]});
const timer=setInterval(()=>{if(free()<8*1024**3)child.kill('SIGTERM');},500);
const code=await new Promise(resolve=>child.on('exit',resolve));clearInterval(timer);fs.closeSync(log);assert.equal(code,0,dir+'/build.log');
const image=JSON.parse(docker('image','inspect',spec.candidate))[0],base=JSON.parse(docker('image','inspect',spec.baseId))[0];
for(const key of ['Env','Entrypoint','Cmd','User','WorkingDir','Healthcheck','ExposedPorts','Volumes'])assert.deepEqual(image.Config[key],base.Config[key],key);
fs.writeFileSync(dir+'/build.json',JSON.stringify({...spec,imageId:image.Id,status:'built-not-verified',date:new Date().toISOString(),productionChanged:false},null,2)+'\n');
console.log(dir);
