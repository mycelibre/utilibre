import assert from 'node:assert/strict';
import fs from 'node:fs';
import cp from 'node:child_process';
import crypto from 'node:crypto';
import path from 'node:path';
const base='utilibre-grist:libraries-security-20261011';
const baseId='sha256:2775bf60ef3a2058d99edb5656e9e4e150662283fce9c88e6d7cd1295583ac80';
const tag='utilibre-grist:1.7.21-deno297-security-20261011';
const dir='/var/lib/utilibre-maintenance/sandbox-final-20261011';
const artifact=path.join(dir,'artifact');
const run=(cmd,args)=>cp.execFileSync(cmd,args,{encoding:'utf8',timeout:120000,stdio:['ignore','pipe','pipe']});
const hash=f=>crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');
assert.equal(run('docker',['image','inspect',base,'--format','{{.Id}}']).trim(),baseId);
assert.ok(fs.statfsSync('/').bavail*fs.statfsSync('/').bsize>8*1024**3,'8GiB root reserve');
fs.mkdirSync(artifact,{recursive:true,mode:0o755});
const url='https://github.com/denoland/deno/releases/download/v2.9.7/deno-x86_64-unknown-linux-gnu.zip';
if(!fs.existsSync(path.join(artifact,'deno.zip')))run('curl',['-fsSL','--max-time','60','--retry','2','-o',path.join(artifact,'deno.zip'),url]);
assert.equal(hash(path.join(artifact,'deno.zip')),'c6527f24f4b16031d3ae4fa9f658d5f11534c8d84ce7dc8502420280919c3490');
run('unzip',['-o',path.join(artifact,'deno.zip'),'-d',artifact]);
assert.equal(hash(path.join(artifact,'deno')),'ce6a052beb97c2b92de67077e3f3924ba7c9661ede0d8dc2f66a116a3c841f21');
const manifest={name:'deno',version:'2.9.7',source:'https://github.com/denoland/deno/tree/v2.9.7',license:'MIT',url,sha256:hash(path.join(artifact,'deno')),archiveSha256:hash(path.join(artifact,'deno.zip')),note:'Official release binary replaces only the native executable. Existing npm loader code remains Grist-pinned; its wrapper version is not the runtime version.'};
fs.writeFileSync(path.join(artifact,'deno-runtime.json'),JSON.stringify(manifest,null,2)+'\n');
fs.copyFileSync(path.resolve('deployment/maintenance/sandbox-final/grist-deno.sh'),path.join(artifact,'grist-deno.sh'));
run('docker',['build','--network','none','--cpuset-cpus','0','--memory','2g','-f',path.resolve('deployment/maintenance/sandbox-final/Dockerfile.grist-pyodide'),'-t',tag,artifact]);
const imageId=run('docker',['image','inspect',tag,'--format','{{.Id}}']).trim();
const receipt={date:new Date().toISOString(),base,baseId,tag,imageId,manifest,productionChanged:false};
fs.writeFileSync(path.join(dir,'build.json'),JSON.stringify(receipt,null,2)+'\n',{mode:0o600});console.log(JSON.stringify(receipt));
